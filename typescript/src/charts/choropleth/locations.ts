const digitsOf = (s: string) => s.replace(/[^0-9]/g, "");

/**
 * The geometry id of a location value at a resolution, or `null`: for a
 * county, its digits zero-padded to five; for a state, its digits
 * zero-padded to two, its postal abbreviation, or its name in any case; for
 * a country, a three-letter code uppercased or a two-letter code mapped to
 * its three-letter code. A number reads as its digits, so FIPS codes stored
 * as numbers recover their leading zeros.
 */
export function normalizeLocation(
  raw: string | number | null | undefined,
  resolution: MapResolution,
): string | null {
  if (raw === null || raw === undefined) return null;
  const s = String(raw).trim();
  if (!s) return null;
  if (resolution === "county") {
    const d = digitsOf(s);
    return d && d.length <= 5 ? d.padStart(5, "0") : null;
  }
  if (resolution === "state") {
    const d = digitsOf(s);
    if (d) return d.length <= 2 ? d.padStart(2, "0") : null;
    return STATE_ABBR_TO_FIPS[s.toUpperCase()] ?? STATE_NAME_TO_FIPS[s.toLowerCase()] ?? null;
  }
  const up = s.toUpperCase();
  if (up.length === 3) return up;
  if (up.length === 2) return ISO2_TO_ISO3[up] ?? null;
  return null;
}
